const tidy = (value: string) => value.replace(/[[\]]/g, '').trim().replace(/\.$/, '')
export function expandBdbPos(value: string): string {
	const normalized = tidy(value)
		.replace(/\s*\.\s*/g, '.')
		.replace(/\s+/g, ' ')
	const tokens = normalized.split(/[. ]/).filter(Boolean)
	if (!tokens.some((token) => token in words)) return value.trim()
	if (tokens.includes('n') && tokens.includes('pr')) {
		const rest = tokens.filter((token) => !['n', 'pr', 'm', 'f', 'loc'].includes(token))
		const name = tokens.includes('loc')
			? 'place name'
			: `${tokens.includes('m') ? 'masculine ' : tokens.includes('f') ? 'feminine ' : ''}proper name`
		return [name, ...rest.map((token) => words[token] ?? token)].join(' ')
	}
	if (tokens[0] === 'n') {
		const modifiers = tokens.slice(1).map((token) => words[token] ?? token)
		return [...modifiers, 'noun'].join(' ')
	}
	return tokens.map((token) => words[token] ?? token).join(' ')
}
export function expandBdbStem(value: string): string {
	return value
		.trim()
		.split(/\s+/)
		.map((token) => stems[tidy(token)] ?? aspects[tidy(token)] ?? expandBdbInline(token))
		.join(' ')
}
export function expandBdbAspect(value: string): string {
	if (
		!tidy(value)
			.split(/[.\s]+/)
			.some((token) => token in aspects) &&
		tidy(value) !== 'st. c'
	)
		return value.trim()
	return tidy(value)
		.replace(/^st\. c$/, 'construct')
		.split(/[.\s]+/)
		.map((token) => aspects[token] ?? token)
		.join(' ')
}
export function expandBdbInline(value: string): string {
	return value.replace(/(?<![\w.])(?:[A-Za-z]+\.)+(?![\w.])/g, (token) => {
		const key = token.slice(0, -1)
		if (inline[key]) return inline[key]
		if (/^(?:n|pr|adj|pron)\./.test(key) && key.split('.').every((part) => words[part]))
			return expandBdbPos(key)
		return token
	})
}
export function expandBdbEmphasis(value: string): string {
	return inline[tidy(value)] ?? expandBdbInline(value)
}
