export type CanonicalBookId = (typeof books)[number]['id']
export function normalizeBookAlias(alias: string): string {
	return alias.toLowerCase().replace(/[.\s]/g, '')
}
export function findBooks(alias: string) {
	const normalized = normalizeBookAlias(alias)
	return books.filter((book) =>
		[book.id, book.name, ...book.aliases].some((value) => normalizeBookAlias(value) === normalized),
	)
}
